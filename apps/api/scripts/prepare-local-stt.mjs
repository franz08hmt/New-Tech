import { createHash } from "node:crypto";
import { createReadStream, createWriteStream } from "node:fs";
import {
  access,
  mkdir,
  realpath,
  readFile,
  rename,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { constants } from "node:fs";
import { Readable, Transform } from "node:stream";
import { pipeline } from "node:stream/promises";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("../../../", import.meta.url));
const model = "onnx-community/whisper-small";
const revision = "dc93399f6d0d35f7eddcb1b3f029d8684f4dfc12";
const transformersJsVersion = "3.8.1";
const manifestName = ".stt-model-manifest.json";
const stagingMarker = ".examate-stt-download-in-progress";
const files = [
  ["added_tokens.json", 128 * 1024],
  ["config.json", 64 * 1024],
  ["generation_config.json", 64 * 1024],
  ["merges.txt", 1024 * 1024],
  ["normalizer.json", 256 * 1024],
  ["preprocessor_config.json", 64 * 1024],
  ["special_tokens_map.json", 128 * 1024],
  ["tokenizer.json", 4 * 1024 * 1024],
  ["tokenizer_config.json", 1024 * 1024],
  ["vocab.json", 2 * 1024 * 1024],
  ["onnx/decoder_model_merged_quantized.onnx", 190 * 1024 * 1024],
  ["onnx/encoder_model_quantized.onnx", 120 * 1024 * 1024],
];

const configuredDirectory =
  process.env.STT_MODEL_DIR?.trim() || "artifacts/stt-models";
const modelDirectory = isAbsolute(configuredDirectory)
  ? configuredDirectory
  : resolve(projectRoot, configuredDirectory);
const modelParent = join(modelDirectory, "onnx-community");
const target = join(modelParent, "whisper-small");
const staging = join(modelParent, ".whisper-small-staging");

await mkdir(modelParent, { recursive: true });
if (await completeModel(target)) {
  console.log(`Whisper model đã có đủ file và đúng revision: ${target}`);
  process.exit(0);
}
if (await exists(target))
  throw new Error(
    `Thư mục model đã tồn tại nhưng chưa hợp lệ: ${target}. Hãy tự kiểm tra và đổi tên thư mục đó trước khi chạy lại.`,
  );
if (await exists(staging)) {
  const markerPath = join(staging, stagingMarker);
  if (!(await exists(markerPath)))
    throw new Error(
      `Thư mục tạm không do lệnh STT tạo; giữ nguyên để kiểm tra: ${staging}`,
    );
  const realParent = await realpath(modelParent);
  const realStaging = await realpath(staging);
  if (
    !realStaging.startsWith(`${realParent}/`) &&
    !realStaging.startsWith(`${realParent}\\`)
  )
    throw new Error(
      "Đường dẫn thư mục tải tạm không nằm trong artifacts/stt-models.",
    );
  await rm(staging, { recursive: true, force: true });
}

await mkdir(staging, { recursive: false });
await writeFile(
  join(staging, stagingMarker),
  "generated by ExaMate local STT prepare script\n",
  {
    flag: "wx",
  },
);
const manifestFiles = {};
let totalBytes = 0;

for (const [relativePath, maxBytes] of files) {
  const destination = join(staging, relativePath);
  await mkdir(dirname(destination), { recursive: true });
  const temporary = `${destination}.partial`;
  const url = `https://huggingface.co/${model}/resolve/${revision}/${relativePath
    .split("/")
    .map(encodeURIComponent)
    .join("/")}?download=true`;
  const response = await fetch(url, {
    redirect: "follow",
    signal: AbortSignal.timeout(120_000),
  });
  if (!response.ok || !response.body)
    throw new Error(
      `Không tải được ${relativePath} (HTTP ${response.status}).`,
    );
  const declaredLength = Number(response.headers.get("content-length"));
  if (Number.isFinite(declaredLength) && declaredLength > maxBytes)
    throw new Error(`File ${relativePath} lớn hơn giới hạn an toàn.`);
  const hash = createHash("sha256");
  let sizeBytes = 0;
  const meter = new Transform({
    transform(chunk, _encoding, callback) {
      sizeBytes += chunk.length;
      if (sizeBytes > maxBytes) {
        callback(new Error(`File ${relativePath} lớn hơn giới hạn an toàn.`));
        return;
      }
      hash.update(chunk);
      callback(null, chunk);
    },
  });
  try {
    await pipeline(
      Readable.fromWeb(response.body),
      meter,
      createWriteStream(temporary, { flags: "wx" }),
    );
    if (!sizeBytes) throw new Error(`File ${relativePath} tải rỗng.`);
    await rename(temporary, destination);
  } catch (error) {
    await rm(temporary, { force: true });
    throw error;
  }
  totalBytes += sizeBytes;
  manifestFiles[relativePath] = { sizeBytes, sha256: hash.digest("hex") };
  console.log(
    `Đã tải ${relativePath} (${(sizeBytes / 1024 / 1024).toFixed(1)} MiB)`,
  );
}

const manifest = {
  version: 1,
  model,
  revision,
  transformersJsVersion,
  files: manifestFiles,
};
await writeFile(
  join(staging, manifestName),
  `${JSON.stringify(manifest, null, 2)}\n`,
  {
    flag: "wx",
  },
);
await rm(join(staging, stagingMarker), { force: true });
await rename(staging, target);
console.log(
  `Hoàn tất: ${target} (${(totalBytes / 1024 / 1024).toFixed(1)} MiB tổng). Không tải các biến thể ONNX khác.`,
);

async function completeModel(directory) {
  try {
    const manifest = JSON.parse(
      await readFile(join(directory, manifestName), "utf8"),
    );
    if (
      manifest.version !== 1 ||
      manifest.model !== model ||
      manifest.revision !== revision ||
      manifest.transformersJsVersion !== transformersJsVersion
    )
      return false;
    for (const [relativePath] of files) {
      const recorded = manifest.files?.[relativePath];
      if (
        !Number.isSafeInteger(recorded?.sizeBytes) ||
        !/^[a-f0-9]{64}$/i.test(recorded?.sha256 || "")
      )
        return false;
      const metadata = await stat(join(directory, relativePath));
      if (!metadata.isFile() || metadata.size !== recorded.sizeBytes)
        return false;
      const hash = createHash("sha256");
      for await (const chunk of createReadStream(join(directory, relativePath)))
        hash.update(chunk);
      if (hash.digest("hex") !== recorded.sha256) return false;
    }
    return true;
  } catch {
    return false;
  }
}

async function exists(path) {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}
